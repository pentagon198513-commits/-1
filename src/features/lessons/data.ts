// Методика: каждый урок вводит минимум новых букв, сразу тренирует их
// в связке с уже изученными. Тексты генерируются из разрешённого алфавита.

function repeatGroups(groups: string[], times: number): string {
  const out: string[] = [];
  for (let i = 0; i < times; i++) out.push(...groups);
  return out.join(' ');
}

